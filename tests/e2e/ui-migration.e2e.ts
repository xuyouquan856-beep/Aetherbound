import { test, expect, _electron as electron } from '@playwright/test';
import { mkdtemp, readFile, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import JSZip from 'jszip';

test('production library theme, settings, collections and responsive layouts', async () => {
  test.setTimeout(150_000);
  const root = await mkdtemp(join(tmpdir(), 'aetherbound-ui-'));
  const coverBytes = await readFile(resolve('build/reader-icon-v2-transparent.png'));
  const paths: string[] = [];
  const names = ['夜空之书 1', '夜空之书 2', '夜空之书 3', 'わたしの魔術コンサルタント 1', 'わたしの魔術コンサルタント 2', '这是一个很长的系列名称用于检查书架和珍藏标题换行是否挤压封面 1', '银色旅途 1', '银色旅途 2'];
  for (let i = 0; i < names.length; i++) {
    const z = new JSZip();
    z.file('mimetype', 'application/epub+zip');
    z.file('META-INF/container.xml', '<container xmlns="urn:oasis:names:tc:opendocument:xmlns:container"><rootfiles><rootfile full-path="book.opf" media-type="application/oebps-package+xml"/></rootfiles></container>');
    z.file('book.opf', `<package xmlns="http://www.idpf.org/2007/opf" version="3.0" unique-identifier="uid"><metadata xmlns:dc="http://purl.org/dc/elements/1.1/"><dc:identifier id="uid">migration-${i}</dc:identifier><dc:title>${names[i]}</dc:title><dc:creator>测试作者</dc:creator><dc:language>zh</dc:language></metadata><manifest><item id="cover" href="cover.png" media-type="image/png" properties="cover-image"/><item id="body" href="body.xhtml" media-type="application/xhtml+xml"/><item id="nav" href="nav.xhtml" media-type="application/xhtml+xml" properties="nav"/></manifest><spine><itemref idref="body"/></spine></package>`);
    z.file('cover.png', coverBytes);
    z.file('body.xhtml', '<html xmlns="http://www.w3.org/1999/xhtml"><body><h1>第一章</h1><p>用于隔离验证的测试正文。</p></body></html>');
    z.file('nav.xhtml', '<html xmlns="http://www.w3.org/1999/xhtml" xmlns:epub="http://www.idpf.org/2007/ops"><body><nav epub:type="toc"><ol><li><a href="body.xhtml">第一章</a></li></ol></nav></body></html>');
    const path = join(root, `${i}.epub`); await writeFile(path, await z.generateAsync({ type: 'nodebuffer' })); paths.push(path);
  }
  let app = await electron.launch({ ...(process.env.READER_E2E_EXECUTABLE ? { executablePath: process.env.READER_E2E_EXECUTABLE, args: [] } : { args: [resolve('out/main/index.js')] }), env: { ...process.env, READER_DATA_ROOT: join(root, 'data'), READER_E2E: '1' } });
  try {
    const page = await app.firstWindow();
    await page.waitForURL(url => url.protocol === 'reader-app:');
    await app.evaluate(({ dialog }, files) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: files }); }, paths);
    await page.evaluate(() => window.readerApi.library.importFiles());
    await expect.poll(() => page.evaluate(async () => (await window.readerApi.library.list()).length)).toBe(8);
    await expect.poll(() => page.evaluate(async () => (await window.readerApi.library.list()).filter(b => b.title.startsWith('夜空')).length)).toBe(3);
    await expect.poll(() => page.evaluate(async () => (await window.readerApi.library.list()).filter(b => b.coverUrl).length)).toBe(8);
    await page.evaluate(async () => {
      const books = await window.readerApi.library.list();
      const first = await window.readerApi.collections.create('夜空之书');
      await window.readerApi.collections.addBooks(first.id, books.filter(b => b.title.startsWith('夜空')).slice(0, 2).map(b => b.id));
      const second = await window.readerApi.collections.create('わたしの魔術コンサルタント・長い珍藏名でも封面と文字が重ならない');
      await window.readerApi.collections.addBooks(second.id, books.filter(b => b.title.startsWith('わたし')).map(b => b.id));
    });
    await page.reload();
    await page.setViewportSize({ width: 1440, height: 1000 });
    const snap = async (name: string) => {
      await page.screenshot({ path: test.info().outputPath(`${name}.png`) });
      expect(await page.locator('.app-shell__page').evaluate(el => el.scrollWidth <= el.clientWidth + 2)).toBe(true);
    };
    await expect(page.locator('.home-hero')).toBeVisible();
    expect(await page.locator('.app-shell').evaluate(el => getComputedStyle(el).getPropertyValue('--accent').trim())).toBe('#a8eaff');
    await expect(page.locator('.hero-cover--front img')).toBeVisible();
    await expect(page.locator('.quote-jewel')).toHaveCount(5);
    await expect(page.locator('.living-sky')).toHaveAttribute('data-flight', 'running');
    const trailPixels = () => page.locator('.butterfly-trails').evaluate((element) => {
      const canvas = element as HTMLCanvasElement;
      const bytes = canvas.getContext('2d')!.getImageData(0, 0, canvas.width, canvas.height).data;
      let visible = 0;
      for (let i = 3; i < bytes.length; i += 4) if (bytes[i] > 12) visible++;
      return visible;
    });
    await expect.poll(trailPixels).toBeGreaterThan(200);
    await snap('home');
    await page.getByRole('button', { name: '导入', exact: true }).click();
    await expect(page.getByRole('menu', { name: '导入菜单' })).toBeVisible();
    await page.keyboard.press('Escape');
    await expect(page.getByRole('menu', { name: '导入菜单' })).toHaveCount(0);
    await expect(page.locator('.dropdown-menu')).toHaveCount(0);

    await page.locator('.living-sky, .quote-jewel').evaluateAll(elements => elements.forEach(el => (el as HTMLElement).style.visibility = 'hidden'));
    const quote = page.locator('.quote-home__text');
    await quote.evaluate(el => { const a = el.getAnimations()[0]; a.pause(); a.currentTime = 300; });
    const silver = await quote.screenshot({ path: test.info().outputPath('silver-base.png') });
    await quote.evaluate(el => { el.getAnimations()[0].currentTime = 2900; });
    const glint = await quote.screenshot({ path: test.info().outputPath('silver-sweep.png') });
    expect(silver.equals(glint)).toBe(false);
    await quote.evaluate(el => el.getAnimations()[0].play());
    await page.locator('.living-sky, .quote-jewel').evaluateAll(elements => elements.forEach(el => (el as HTMLElement).style.visibility = ''));
    await page.getByRole('button', { name: '全部书籍', exact: true }).click();
    await snap('books');
    await page.getByRole('button', { name: '列表', exact: true }).click();
    await snap('books-list');
    await page.getByRole('searchbox', { name: '搜索全部书籍' }).fill('夜空');
    await page.getByRole('button', { name: '我的珍藏', exact: true }).click();
    await snap('collections');
    await page.getByRole('button', { name: '新建珍藏', exact: true }).click();
    await expect(page.getByRole('dialog', { name: '新建珍藏' })).toBeVisible();
    await page.getByRole('dialog').getByRole('button', { name: '取消', exact: true }).click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await page.getByRole('button', { name: '新建珍藏', exact: true }).click();
    await expect(page.getByRole('dialog', { name: '新建珍藏' })).toBeVisible();
    await page.keyboard.press('Escape');
    await expect(page.locator('.collection-editor')).toHaveCount(0);
    await expect.poll(() => page.locator('.app-sidebar__nav').evaluate(nav => {
      const active = nav.querySelector<HTMLElement>('[aria-current="page"]')!;
      const indicator = nav.querySelector<HTMLElement>('.sidebar-selection')!;
      return Math.abs(new DOMMatrix(getComputedStyle(indicator).transform).m42 - active.offsetTop) < 1;
    })).toBe(true);

    await page.setViewportSize({ width: 760, height: 820 });
    await snap('narrow-collections');
    await expect(page.locator('.app-sidebar__poem')).not.toBeVisible();
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.getByRole('button', { name: /打开珍藏《夜空/ }).click();
    await snap('collection-detail');
    await page.getByRole('button', { name: '珍藏配色', exact: true }).click();
    await page.getByRole('button', { name: '淡紫', exact: true }).click();
    await page.getByRole('slider', { name: /封面染色程度/ }).fill('24');
    await expect(page.locator('.collection-detail')).toHaveCSS('--crystal-color', '#bba6ff');
    await snap('crystal-detail-settings');
    await page.getByRole('button', { name: '未整理', exact: true }).click();
    await snap('unorganized');
    await page.getByRole('button', { name: /检查系列/ }).first().click();
    await snap('series-review');
    await page.setViewportSize({ width: 760, height: 820 });
    await snap('narrow-review');
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.getByRole('button', { name: '扫描书库', exact: true }).click();
    await snap('scan');
    await page.getByRole('button', { name: '设置', exact: true }).click();
    await expect(page.getByRole('switch', { name: '流光动效' })).toBeChecked();
    await page.getByRole('button', { name: '玫瑰', exact: true }).click();
    await expect(page.locator('.crystal-settings-preview .crystal-collection')).toHaveCSS('--crystal-color', '#f7adc9');
    await snap('settings');
    expect(await app.evaluate(({ Menu }) => Menu.getApplicationMenu() === null)).toBe(true);
    expect(await page.locator('.window-titlebar').evaluate(el => getComputedStyle(el).getPropertyValue('-webkit-app-region'))).toBe('drag');
    await page.getByRole('button', { name: '选择主封面', exact: true }).click();
    await page.getByRole('searchbox', { name: '搜索展示书籍' }).fill('夜空之书 1');
    await page.locator('.home-display-results button').click();
    await page.getByRole('button', { name: '选择副封面', exact: true }).click();
    await page.getByRole('searchbox', { name: '搜索展示书籍' }).fill('夜空之书 2');
    await page.locator('.home-display-results button').click();
    await page.getByRole('button', { name: '交换位置', exact: true }).click();
    await snap('custom-display-settings');
    await page.getByRole('button', { name: '书房', exact: true }).click();
    await expect(page.locator('.hero-cover--front')).toContainText('夜空之书 2');
    await expect(page.locator('.hero-cover--back')).toContainText('夜空之书 1');
    await expect(page.locator('.library-home__masthead').getByRole('button', { name: '导入', exact: true })).toBeVisible();
    await page.reload();
    await expect(page.locator('.hero-cover--front')).toContainText('夜空之书 2');
    expect(await page.evaluate(() => document.documentElement.scrollHeight <= innerHeight + 2)).toBe(true);
    await page.getByRole('button', { name: '全部书籍', exact: true }).click();
    await page.getByRole('searchbox', { name: '搜索全部书籍' }).fill('夜空');
    await page.getByRole('button', { name: '设置', exact: true }).click();
    await page.getByRole('switch', { name: '流光动效' }).click();
    await expect(page.locator('.living-sky')).toHaveAttribute('data-flight', 'paused');
    await expect.poll(trailPixels).toBe(0);
    await page.getByRole('switch', { name: '收起侧栏' }).click();
    await expect(page.locator('.app-shell')).toHaveAttribute('data-collapsed', 'true');
    await page.getByRole('button', { name: /语句库/ }).click();
    await snap('quotes');
    await page.getByRole('button', { name: '返回设置' }).click();
    await page.getByRole('switch', { name: '收起侧栏' }).click();
    await page.getByRole('button', { name: '全部书籍', exact: true }).click();
    await expect(page.getByRole('searchbox')).toHaveValue('夜空');
    await page.setViewportSize({ width: 760, height: 820 });
    await snap('narrow-books');
    await page.reload();
    await expect(page.locator('.app-shell')).toHaveAttribute('data-motion', 'off');
    await snap('narrow-home');
    await app.close();
    app = await electron.launch({ ...(process.env.READER_E2E_EXECUTABLE ? { executablePath: process.env.READER_E2E_EXECUTABLE, args: [] } : { args: [resolve('out/main/index.js')] }), env: { ...process.env, READER_DATA_ROOT: join(root, 'data'), READER_E2E: '1' } });
    const reopened = await app.firstWindow();
    await reopened.setViewportSize({ width: 1440, height: 1000 });
    await expect(reopened.locator('.hero-cover--front')).toContainText('夜空之书 2');
    await expect(reopened.locator('.hero-cover--back')).toContainText('夜空之书 1');
    expect(await app.evaluate(({ Menu }) => Menu.getApplicationMenu() === null)).toBe(true);
    await reopened.getByRole('button', { name: '我的珍藏', exact: true }).click();
    await expect(reopened.locator('.crystal-collection').filter({ has: reopened.getByRole('button', { name: /打开珍藏《夜空/ }) })).toHaveCSS('--crystal-color', '#bba6ff');
    await expect(reopened.locator('.crystal-collection').filter({ has: reopened.getByRole('button', { name: /打开珍藏《わたし/ }) })).toHaveCSS('--crystal-color', '#f7adc9');
    await reopened.screenshot({ path: test.info().outputPath('crystal-colors-persisted.png') });
    await reopened.getByRole('button', { name: '设置', exact: true }).click();
    await reopened.getByRole('button', { name: '自动选择', exact: true }).click();
    await reopened.getByRole('button', { name: '书房', exact: true }).click();
    await expect(reopened.locator('.hero-cover--front')).toContainText(await reopened.locator('.home-hero__book-title').innerText());
  } finally { await app.close(); await rm(root, { recursive: true, force: true }); }
});
